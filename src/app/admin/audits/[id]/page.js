import Link from 'next/link';
import { notFound } from 'next/navigation';
import { ChevronLeft, Download, Mail, MessageCircle } from 'lucide-react';
import { prisma } from '@/lib/prisma';
import { AuditLive } from '@/components/audit-live';
import { AuditReport } from '@/components/audit-report';
import { JsonView } from '@/components/json-view';
import { PageHeader, Panel } from '@/components/page-header';
import { RunAuditButton } from '@/components/run-audit-button';
import { StatusBadge } from '@/components/status-badge';
import { Button } from '@/components/ui/button';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { duration, formatDateTime, hostname } from '@/lib/format';
import { cn } from '@/lib/utils';

export const dynamic = 'force-dynamic';

export async function generateMetadata({ params }) {
  const audit = await prisma.audit.findUnique({ where: { id: params.id }, select: { client: { select: { name: true } } } });
  return { title: audit ? `Audit for ${audit.client.name}` : 'Audit' };
}

const CHANNEL = {
  whatsapp: { label: 'WhatsApp', icon: MessageCircle },
  email: { label: 'Email', icon: Mail },
};

const DELIVERY = { mock_sent: 'Sent (mock)', sent: 'Sent', failed: 'Failed' };

function Meta({ label, children }) {
  return (
    <div>
      <dt className="text-xs text-muted-foreground">{label}</dt>
      <dd className="mt-0.5 text-sm">{children}</dd>
    </div>
  );
}

function Delivery({ audit }) {
  return (
    <div className="grid gap-6 lg:grid-cols-2">
      <Panel title="Notifications" description="Each channel the report was sent on." bodyClassName="p-0">
        {audit.notifications.length ? (
          <ul className="divide-y">
            {audit.notifications.map((n) => {
              const channel = CHANNEL[n.channel] || { label: n.channel, icon: Mail };
              return (
                <li key={n.id} className="flex items-center gap-3 px-5 py-3.5">
                  <channel.icon className="size-4 text-muted-foreground" />
                  <div className="min-w-0 flex-1">
                    <p className="text-sm font-medium">{channel.label}</p>
                    <p className="truncate text-xs text-muted-foreground">{n.providerId || 'No provider id'}</p>
                  </div>
                  <span className={cn('text-sm', n.status === 'failed' ? 'text-poor' : 'text-good')}>
                    {DELIVERY[n.status] || n.status}
                  </span>
                </li>
              );
            })}
          </ul>
        ) : (
          <p className="px-5 py-6 text-sm text-muted-foreground">Nothing sent yet.</p>
        )}
      </Panel>
      <Panel title="PDF report" description="Generated by Puppeteer after the result is saved.">
        {audit.pdfPath ? (
          <div className="space-y-4">
            <p className="break-all rounded-md bg-muted px-3 py-2 text-xs">{audit.pdfPath}</p>
            <Button asChild variant="outline">
              <a href={`/api/audit/${audit.id}/pdf`}>
                <Download className="size-4" />
                Download PDF
              </a>
            </Button>
          </div>
        ) : (
          <p className="text-sm text-muted-foreground">The PDF has not been generated.</p>
        )}
      </Panel>
    </div>
  );
}

export default async function AuditPage({ params }) {
  const audit = await prisma.audit.findUnique({
    where: { id: params.id },
    include: { client: true, notifications: { orderBy: { createdAt: 'asc' } } },
  });
  if (!audit) notFound();

  const { client, result, signals } = audit;
  const live = audit.status !== 'COMPLETED';
  const analysedBy = signals?.meta?.analysedBy;
  const fallbackReason = signals?.meta?.fallbackReason;
  const analysisNote = fallbackReason
    ? `Claude was unavailable (${fallbackReason}), so the built-in analysis produced this report.`
    : analysedBy === 'mock'
      ? 'Mock response returned because USE_MOCKS is on and no Anthropic key is set.'
      : `Returned by ${analysedBy} and validated against the audit schema.`;

  return (
    <>
      <PageHeader
        title={client.name}
        description={`Audit of ${hostname(client.websiteUrl)}`}
        actions={
          <>
            {audit.pdfPath && (
              <Button asChild variant="outline">
                <a href={`/api/audit/${audit.id}/pdf`}>
                  <Download className="size-4" />
                  PDF
                </a>
              </Button>
            )}
            <RunAuditButton clientId={client.id} label="Run again" variant={live ? 'outline' : 'default'} />
          </>
        }
      >
        <Link
          href={`/admin/clients/${client.id}`}
          className="mb-3 inline-flex items-center gap-1 text-sm text-muted-foreground hover:text-foreground"
        >
          <ChevronLeft className="size-4" />
          {client.name}
        </Link>
      </PageHeader>

      <dl className="mb-6 grid grid-cols-2 gap-4 rounded-lg border bg-card p-5 sm:grid-cols-4">
        <Meta label="Status">
          <StatusBadge status={audit.status} />
        </Meta>
        <Meta label="Trigger">{audit.triggeredBy === 'cron' ? 'Monthly schedule' : 'Manual'}</Meta>
        <Meta label="Started">{formatDateTime(audit.createdAt)}</Meta>
        <Meta label="Duration">{duration(audit.createdAt, audit.completedAt) || 'Running'}</Meta>
      </dl>

      {live && (
        <div className="mb-6">
          <AuditLive
            auditId={audit.id}
            initial={{
              status: audit.status,
              progress: audit.progress,
              currentStep: audit.currentStep,
              overallScore: audit.overallScore,
              errorMessage: audit.errorMessage,
            }}
          />
        </div>
      )}

      {result && (
        <Tabs defaultValue="report">
          <TabsList className="mb-4">
            <TabsTrigger value="report">Report</TabsTrigger>
            <TabsTrigger value="json">Claude JSON</TabsTrigger>
            <TabsTrigger value="signals">Signals</TabsTrigger>
            <TabsTrigger value="delivery">Delivery</TabsTrigger>
          </TabsList>
          <TabsContent value="report">
            <AuditReport result={result} />
          </TabsContent>
          <TabsContent value="json">
            <JsonView
              value={result}
              title="Structured analysis"
              description={analysisNote}
            />
          </TabsContent>
          <TabsContent value="signals">
            <JsonView
              value={signals}
              title="Collected signals"
              description="Raw crawl output and the PageSpeed, Search Console and DataForSEO data sent to Claude."
            />
          </TabsContent>
          <TabsContent value="delivery">
            <Delivery audit={audit} />
          </TabsContent>
        </Tabs>
      )}
    </>
  );
}
